#!/usr/bin/env python3
"""Generate the constant tables that the PS1 build links in.

Host-side table synthesis only; nothing here runs on the console. Output is
deterministic so a clean build reproduces byte-identical ROMs.
"""
import math
import pathlib
import sys

OUT = pathlib.Path(sys.argv[1] if len(sys.argv) > 1 else "src/tables.c")

ANG = 4096      # angle units in a full turn
ONE = 4096      # Q12


def sine_table():
    vals = []
    for i in range(ANG):
        v = int(round(math.sin(2.0 * math.pi * i / ANG) * ONE))
        vals.append(max(-ONE, min(ONE, v)))
    return vals


def unr_table():
    """The GTE's 257-entry Newton-Raphson reciprocal seed table.

    Only the host GTE model uses it; on the console the hardware owns it. The
    generator is the one documented in psx-spx.
    """
    return [max(0, (0x40000 // (i + 0x100) + 1) // 2 - 0x101) for i in range(257)]


def emit(name, values, ctype, per_line):
    out = ["const %s %s[%d] = {" % (ctype, name, len(values))]
    for i in range(0, len(values), per_line):
        out.append("    " + ", ".join(str(v) for v in values[i:i + per_line]) + ",")
    out.append("};")
    return "\n".join(out)


def main():
    body = [
        "/* GENERATED by tools/gen_tables.py - do not edit. */",
        '#include "fixed.h"',
        "",
        emit("di_sin_tab", sine_table(), "s16", 16),
        "",
        "/* Reciprocal seeds for the host-side GTE divider model. */",
        emit("di_gte_unr_tab", unr_table(), "u8", 16),
        "",
    ]
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(body) + "\n")
    print("wrote %s (%d bytes)" % (OUT, OUT.stat().st_size))


if __name__ == "__main__":
    main()
